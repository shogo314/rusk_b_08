//! Assemble the C++ target from LIR and its separate native runtime bindings.
use super::{FunctionInfo, cpp};
use crate::lir::{Program, ProgramFunction};
use std::collections::BTreeMap;
pub(crate) struct Context {
    pub types: BTreeMap<String, String>,
    pub functions: Vec<FunctionInfo>,
    pub prelude: String,
    pub foreign_definitions: Vec<String>,
    pub epilogue: String,
}
fn signature(function: &ProgramFunction, context: &Context, optimize: bool) -> String {
    let result = if function.result == "Unit" {
        "void".into()
    } else {
        format!("Obj<{}>", context.types[&function.result])
    };
    let mut params = function
        .params
        .iter()
        .enumerate()
        .map(|(i, t)| {
            let borrowed = optimize && super::borrows_parameter(function, i);
            if borrowed {
                format!("const Obj<{}>& rusk_p{i}", context.types[t])
            } else {
                format!("Obj<{}> rusk_p{i}", context.types[t])
            }
        })
        .collect::<Vec<_>>();
    params.push("[[maybe_unused]] Loc rusk_call_loc".into());
    format!(
        "{result} {}({})",
        context.functions[function.id].cpp,
        params.join(",")
    )
}
pub(crate) fn emit(program: &Program, context: &Context, optimize: bool) -> String {
    let mut out = String::from("// Generated by Rusk beta. C++20, GCC/Clang checked arithmetic.\n");
    out += &context.prelude;
    for f in &program.functions {
        if f.body.is_some() {
            out += &signature(f, context, optimize);
            out += ";\n";
        }
    }
    for native in &context.foreign_definitions {
        out += native;
        out += "\n";
    }
    for f in &program.functions {
        if let Some(body) = &f.body {
            out += &format!(
                "// Rusk function {}: {}\n{} {{\n{}\n}}\n",
                f.id,
                f.name,
                signature(f, context, optimize),
                cpp(
                    body,
                    &context.types,
                    &context.functions,
                    &program.functions,
                    optimize,
                    Some(f)
                )
            );
        }
    }
    out += &context.epilogue;
    out += "int main() {\n";
    out += &cpp(
        &program.main,
        &context.types,
        &context.functions,
        &program.functions,
        optimize,
        None,
    );
    out += "}\n";
    out
}
