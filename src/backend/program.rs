//! Assemble the C++ target from LIR and its separate native runtime bindings.
use super::{FunctionInfo, cpp};
use crate::lir::{Program, ProgramFunction};
use std::collections::BTreeMap;
pub(crate) struct Context {
    pub types: BTreeMap<String, String>,
    pub functions: Vec<FunctionInfo>,
    pub prelude: String,
    pub foreign_definitions: Vec<String>,
    pub native_unit_bridges: std::collections::BTreeSet<(usize, crate::native_abi::UnitBridge)>,
    pub native_declarations: std::collections::BTreeSet<usize>,
    pub native_value_references: std::collections::BTreeSet<usize>,
    pub native_effect_references: std::collections::BTreeSet<(usize, crate::effects::Query)>,
    pub epilogue: String,
}
fn signature(function: &ProgramFunction, context: &Context, optimize: bool) -> String {
    let result = if function.result == "Unit" && !context.functions[function.id].unit_object {
        "void".into()
    } else {
        format!("Obj<{}>", context.types[&function.result])
    };
    let mut params = function
        .params
        .iter()
        .enumerate()
        .map(|(i, t)| {
            let borrowed = optimize && super::borrows_parameter(function, i);
            if borrowed {
                format!("const Obj<{}>& rusk_p{i}", context.types[t])
            } else {
                format!("Obj<{}> rusk_p{i}", context.types[t])
            }
        })
        .collect::<Vec<_>>();
    params.push("[[maybe_unused]] Loc rusk_call_loc".into());
    format!(
        "{result} {}({})",
        context.functions[function.id].cpp,
        params.join(",")
    )
}
pub(crate) fn emit(program: &Program, context: &Context, optimize: bool) -> String {
    let mut out = String::from("// Generated by Rusk beta. C++20, GCC/Clang checked arithmetic.\n");
    out += &context.prelude;
    for f in &program.functions {
        if f.body.is_some() || context.native_declarations.contains(&f.id) {
            out += &signature(f, context, optimize);
            out += ";\n";
        }
    }
    // Native bodies may call these value-returning adapters, including adapters
    // to Rusk bodies defined later. All ordinary prototypes precede them.
    for (id, query) in &context.native_effect_references {
        out += &format!(
            "constexpr bool rusk_{}_{id} = {};\n",
            query.name(),
            query.evaluate(&program.functions[*id].effects)
        );
    }
    for (id, bridge) in &context.native_unit_bridges {
        let f = &program.functions[*id];
        let args = (0..f.params.len())
            .map(|i| format!("rusk_a{i}"))
            .collect::<Vec<_>>();
        let mut params = f
            .params
            .iter()
            .zip(&args)
            .map(|(ty, arg)| format!("const Obj<{}>& {arg}", context.types[ty]))
            .collect::<Vec<_>>();
        params.push("[[maybe_unused]] Loc rusk_loc".into());
        let mut actual = args;
        actual.push("rusk_loc".into());
        let result = match bridge {
            crate::native_abi::UnitBridge::Discard => "void".into(),
            crate::native_abi::UnitBridge::Box => format!("Obj<{}>", context.types["Unit"]),
        };
        let finish = match bridge {
            crate::native_abi::UnitBridge::Discard => String::new(),
            crate::native_abi::UnitBridge::Box => format!(
                "return make_obj<{}>({}{{}});",
                context.types["Unit"], context.types["Unit"]
            ),
        };
        out += &format!(
            "{result} {}({}){{{}({});{finish}}}\n",
            bridge.name(*id),
            params.join(","),
            context.functions[*id].cpp,
            actual.join(",")
        );
    }
    for id in &context.native_value_references {
        let f = &program.functions[*id];
        let mut params = f
            .params
            .iter()
            .map(|ty| format!("const Obj<{}>&", context.types[ty]))
            .collect::<Vec<_>>();
        params.push("Loc".into());
        out += &format!(
            "{} rusk_value_ref_{id}({});\n",
            context.types[&f.result],
            params.join(",")
        );
    }
    for id in &context.native_value_references {
        let f = &program.functions[*id];
        let info = &context.functions[*id];
        let args = (0..f.params.len())
            .map(|i| format!("rusk_a{i}"))
            .collect::<Vec<_>>();
        let mut params = f
            .params
            .iter()
            .zip(&args)
            .map(|(ty, arg)| format!("const Obj<{}>& {arg}", context.types[ty]))
            .collect::<Vec<_>>();
        params.push("[[maybe_unused]] Loc rusk_loc".into());
        let expression = info
            .lowering
            .as_ref()
            .filter(|_| info.trusted)
            .and_then(|l| l.scalar.as_ref())
            .map(|t| t.render(&args, "rusk_loc"))
            .unwrap_or_else(|| {
                let mut call_args = args.clone();
                call_args.push("rusk_loc".into());
                format!("*{}({})", info.cpp, call_args.join(","))
            });
        out += &format!(
            "{} rusk_value_ref_{id}({}){{return {expression};}}\n",
            context.types[&f.result],
            params.join(",")
        );
    }
    for native in &context.foreign_definitions {
        out += native;
        out += "\n";
    }
    for f in &program.functions {
        if let Some(body) = &f.body {
            out += &format!(
                "// Rusk function {}: {}\n{} {{\n{}\n}}\n",
                f.id,
                f.name,
                signature(f, context, optimize),
                cpp(
                    body,
                    &context.types,
                    &program.types,
                    &context.functions,
                    &program.functions,
                    optimize,
                    Some(f)
                )
            );
        }
    }
    out += &context.epilogue;
    out += "int main() {\n";
    out += &cpp(
        &program.main,
        &context.types,
        &program.types,
        &context.functions,
        &program.functions,
        optimize,
        None,
    );
    out += "}\n";
    out
}
